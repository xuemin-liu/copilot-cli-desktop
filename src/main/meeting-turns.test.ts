import assert from 'node:assert/strict'
import test from 'node:test'
import { MeetingTurnReader, confirmedMeetingReply } from './meeting-turns.js'

const record = (type: string, data: Record<string, unknown>, extra: Record<string, unknown> = {}): string => JSON.stringify({ type, data, ...extra })
const user = (content: string, interactionId = 'i1'): string => record('user.message', { content, interactionId })
const assistant = (data: Record<string, unknown>): string => record('assistant.message', { interactionId: 'i1', ...data })

test('the final answer is the reply; commentary and tool-call messages before it are not', () => {
  const reader = new MeetingTurnReader()
  assert.deepEqual(reader.consume(user('Review this')), { content: 'Review this', desktop: false })
  reader.consume(assistant({ content: 'I will look at the files.', phase: 'commentary', toolRequests: [{ id: 't' }] }))
  reader.consume(record('assistant.turn_end', { turnId: '1' }))
  reader.consume(assistant({ content: 'Step 2 is racy.', phase: 'final_answer', toolRequests: [] }))
  reader.consume(assistant({ content: '', toolRequests: [] }))
  assert.deepEqual(reader.finish(), { content: 'Review this', desktop: false, reply: 'Step 2 is racy.', failure: null })
  assert.equal(reader.finish(), null, 'reported once')
})

/** One model step that ends with no final answer, as a failed model call does. */
const failedStep = (reader: MeetingTurnReader, turnId: string): void => {
  reader.consume(record('assistant.turn_start', { turnId }))
  reader.consume(record('assistant.turn_end', { turnId }))
}

test('a model error after a turn with no final answer marks it failed, whatever text came before; a turn that starts after it clears the mark', () => {
  const reader = new MeetingTurnReader()
  reader.expectDesktopPrompt()
  reader.consume(user('[meeting K7QF · round 1 · from the desktop]'))
  reader.consume(record('assistant.turn_start', { turnId: '1' }))
  reader.consume(assistant({ content: 'Looking at the files.', toolRequests: [{ id: 't' }] }))
  reader.consume(record('assistant.turn_end', { turnId: '1' }))
  reader.consume(record('session.error', { errorType: 'query', message: '400 The `reasoning_content` must be passed back.' }))
  const failed = reader.finish()
  assert.equal(failed?.failure, '400 The `reasoning_content` must be passed back.')
  assert.equal(failed?.desktop, true)

  reader.consume(user('Next', 'i2'))
  failedStep(reader, '2')
  reader.consume(record('session.error', { message: 'x' }))
  reader.consume(record('assistant.turn_start', { turnId: '3' }))
  assert.equal(reader.finish()?.failure, null)

  reader.consume(user('No message', 'i3'))
  failedStep(reader, '4')
  reader.consume(record('session.error', {}))
  assert.equal(reader.finish()?.failure, 'The model failed.')
  reader.consume(user('Long', 'i4'))
  failedStep(reader, '5')
  reader.consume(record('session.error', { message: 'x'.repeat(1_000) }))
  assert.equal(reader.finish()?.failure?.length, 300)

  reader.consume(user('A subagent failed', 'i5'))
  failedStep(reader, '6')
  reader.consume(record('session.error', { message: 'child' }, { agentId: 'child' }))
  assert.equal(reader.finish()?.failure, null)
})

test('a model error the activity tracker ignores does not fail the turn, so its answer still counts', () => {
  const reader = new MeetingTurnReader()
  const answered = (data: Record<string, unknown>): string => record('assistant.message', { interactionId: 'i1', ...data })
  reader.expectDesktopPrompt()
  reader.consume(user('[meeting K7QF · round 1 · from the desktop]'))
  reader.consume(record('assistant.turn_start', { turnId: '1' }))
  reader.consume(record('session.error', { message: 'a transient error during the turn' }))
  reader.consume(answered({ content: 'My full review: step 2 races.', phase: 'final_answer', toolRequests: [] }))
  reader.consume(record('assistant.turn_end', { turnId: '1' }))
  assert.deepEqual(reader.finish(), { content: '[meeting K7QF · round 1 · from the desktop]', desktop: true, reply: 'My full review: step 2 races.', failure: null })

  reader.consume(user('After an answer', 'i2'))
  reader.consume(record('assistant.turn_start', { turnId: '2' }))
  reader.consume(record('assistant.message', { interactionId: 'i2', content: 'Done.', toolRequests: [] }))
  reader.consume(record('assistant.turn_end', { turnId: '2' }))
  reader.consume(record('session.error', { message: 'after the turn was answered' }))
  assert.equal(reader.finish()?.failure, null)

  reader.reset('monitor-attached')
  reader.consume(user('After a gap in the log', 'i3'))
  reader.consume(record('session.error', { message: 'no turn seen since the gap' }))
  assert.equal(reader.finish()?.failure, null)
})

test('without a phase (older CLIs) the reply is the last message with text and no tool requests', () => {
  const reader = new MeetingTurnReader()
  reader.consume(user('Review this'))
  reader.consume(assistant({ content: 'Looking.', toolRequests: [{ id: 't' }] }))
  reader.consume(assistant({ content: 'First thought.', toolRequests: [] }))
  reader.consume(assistant({ content: 'Final answer.' }))
  assert.equal(reader.finish()?.reply, 'Final answer.')
})

test('the prompt the desktop typed is marked as the desktop\'s; the next one the person types is not', () => {
  const reader = new MeetingTurnReader()
  reader.expectDesktopPrompt()
  assert.equal(reader.consume(user('[Pasted text] ...'))?.desktop, true, 'by expectation, whatever the CLI recorded')
  assert.equal(reader.answeringPerson, false)
  reader.finish()
  assert.equal(reader.consume(user('join meeting K7QF', 'i2'))?.desktop, false)
  assert.equal(reader.answeringPerson, true)
  assert.equal(reader.consume(user('[meeting K7QF · round 1 · from the desktop]\n...', 'i3'))?.desktop, true, 'by its marker')
})

test('a typed prompt that never arrived does not claim the person\'s next message (meeting W7A4)', () => {
  const reader = new MeetingTurnReader()
  reader.expectDesktopPrompt('Investigate this source in the dedicated checkout.\nExpected revision: abc')
  assert.equal(reader.desktopPromptCount, 0)
  assert.equal(reader.consume(user('why are you stuck?'))?.desktop, false, 'an unrelated prompt is the person\'s')
  assert.equal(reader.answeringPerson, true)
  assert.equal(reader.diagnostic.expectingDesktop, false, 'the expectation is settled, not carried to a later prompt')
  assert.equal(reader.desktopPromptCount, 0, 'the delivery is not confirmed')
  reader.finish()
  assert.equal(reader.consume(user('Investigate this source in the dedicated checkout.', 'i2'))?.desktop, false, 'nor is a later look-alike')
})

test('only a turn confirmed as the typed prompt yields a meeting reply; the person\'s turn or no turn does not', () => {
  const reader = new MeetingTurnReader()
  reader.expectDesktopPrompt('[meeting W7A4 · round 1 · from the desktop]\nReview this')
  reader.consume(user('why are you stuck?'))
  reader.consume(JSON.stringify({ type: 'assistant.message', data: { content: 'Waiting for the meeting material.', toolRequests: [] } }))
  assert.equal(confirmedMeetingReply(reader.finish()), null, 'the person\'s answer is not recorded as the review')
  assert.equal(confirmedMeetingReply(reader.finish()), null, 'idle with no prompt recorded is not an empty review')
  reader.expectDesktopPrompt('[meeting W7A4 · round 2 · from the desktop]\nReview this')
  reader.consume(user('[meeting W7A4 · round 2 · from the desktop]\nReview this', 'i2'))
  reader.consume(JSON.stringify({ type: 'assistant.message', data: { content: 'Looks good.', toolRequests: [] } }))
  assert.equal(confirmedMeetingReply(reader.finish()), 'Looks good.')
})

test('the expected prompt is confirmed by its text, CRLF and surrounding whitespace aside, or by a paste placeholder', () => {
  const reader = new MeetingTurnReader()
  reader.expectDesktopPrompt('  Investigate this source.\r\nExpected revision: abc')
  assert.equal(reader.consume(user('Investigate this source.\nExpected revision: abc'))?.desktop, true)
  assert.equal(reader.desktopPromptCount, 1)
  reader.finish()
  reader.expectDesktopPrompt('Investigate this source.')
  assert.equal(reader.consume(user('[Paste #1 - 40 lines]', 'i2'))?.desktop, true, 'older CLIs record a placeholder')
  assert.equal(reader.desktopPromptCount, 2)
  reader.finish()
  reader.expectDesktopPrompt('[meeting K7QF · round 2 · from the desktop]\nReview this')
  assert.equal(reader.consume(user('[meeting K7QF · round 2 · from the desktop]\nReview this', 'i3'))?.desktop, true)
  assert.equal(reader.desktopPromptCount, 3)
  reader.expectDesktopPrompt('Investigate this source.')
  reader.reset('monitor-attached')
  assert.equal(reader.consume(user('Investigate this source.', 'i4'))?.desktop, false, 'a new monitor drops the expectation')
})

test('subagent records, other interactions and unreadable lines are ignored; chunked messages are joined', () => {
  const reader = new MeetingTurnReader()
  reader.consume(user('Review this'))
  reader.consume(record('assistant.message', { content: 'subagent', phase: 'final_answer', interactionId: 'i1' }, { agentId: 'a1' }))
  reader.consume(record('assistant.message', { content: 'nested', phase: 'final_answer', interactionId: 'i1', parentToolCallId: 't' }))
  reader.consume(record('assistant.message', { content: 'other', phase: 'final_answer', interactionId: 'i9' }))
  reader.consume('{not json')
  reader.consume(assistant({ content: 'world', phase: 'final_answer', messageId: 'm', chunkIndex: 1, chunkCount: 2 }))
  reader.consume(assistant({ content: 'hello ', phase: 'final_answer', messageId: 'm', chunkIndex: 0, chunkCount: 2 }))
  assert.equal(reader.finish()?.reply, 'hello world')
})

test('usage totals come from checkpoints, in history too; only history never yields a prompt', () => {
  const reader = new MeetingTurnReader()
  const checkpoint = (nanoAiu: number, premium: number): string => record('session.usage_checkpoint', { totalNanoAiu: nanoAiu, totalPremiumRequests: premium })
  assert.equal(reader.usage, null)
  assert.equal(reader.consume(user('join meeting K7QF'), false), null, 'a prompt in history is not acted on')
  reader.consume(checkpoint(2e9, 1), false)
  assert.deepEqual(reader.usage, { nanoAiu: 2e9, premiumRequests: 1 })
  assert.equal(reader.takeUsageChange(), null, 'history is the baseline, not a change')
  reader.consume(checkpoint(3e9, 1))
  assert.deepEqual(reader.takeUsageChange(), { nanoAiu: 3e9, premiumRequests: 1 })
  assert.equal(reader.takeUsageChange(), null, 'once')
  reader.consume(record('session.usage_checkpoint', { totalNanoAiu: 'lots', totalPremiumRequests: -4 }))
  assert.deepEqual(reader.usage, { nanoAiu: 0, premiumRequests: 0 }, 'unreadable values count as nothing')
})

